def section(path: Path, title: str, stop_prefix: str | None = None) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    start = None
    for index, line in enumerate(lines):
        if line == f"## {title}":
            start = index
            break
    if start is None:
        raise SystemExit(f"missing heading: {title} in {path}")
    end = len(lines)
    for index in range(start + 1, len(lines)):
        if lines[index].startswith("## "):
            end = index
            break
    chunk = lines[start:end]
    if stop_prefix:
        for index, line in enumerate(chunk):
            if line.startswith(stop_prefix):
                chunk = chunk[:index]
                break
    text = "\n".join(chunk).strip()
    if not text:
        raise SystemExit(f"empty section: {title}")
    return text + "\n"


def span(path: Path, start: int, end: int) -> str:
    """1-based inclusive line slice, unchanged."""
    rows = path.read_text(encoding="utf-8").splitlines()
    text = "\n".join(rows[start - 1 : end]).strip()
    if not text:
        raise SystemExit(f"empty span {path} {start}-{end}")
    return text + "\n"


def preamble_until(path: Path, stop_prefix: str) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    end = len(lines)
    for index, line in enumerate(lines):
        if line.startswith("## ") or line.startswith(stop_prefix):
            end = index
            break
    body = "\n".join(lines[1:end]).strip()
    if not body:
        raise SystemExit(f"empty preamble: {path}")
    return body + "\n"


